class RolloutViolationError(ValueError):
    """A typed failure that never carries physical writer capability."""

    def __init__(self, code: RolloutCode, detail: str) -> None:
        super().__init__(f"{code.value}: {detail}")
        self.code = code


RolloutViolation = RolloutViolationError
