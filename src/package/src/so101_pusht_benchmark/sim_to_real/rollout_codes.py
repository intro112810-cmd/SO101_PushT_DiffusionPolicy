    R_DUPLICATE_SAMPLE = "R_DUPLICATE_SAMPLE"
    R_DUPLICATE_HISTORY = "R_DUPLICATE_HISTORY"
    EQUIVALENCE_UNPROVEN = "EQUIVALENCE_UNPROVEN"
    CAMERA_UNREGISTERED = "CAMERA_UNREGISTERED"
    HISTORY_INCOMPLETE = "HISTORY_INCOMPLETE"
    R_CAMERA_EQUIVALENCE_UNPROVEN = "R_CAMERA_EQUIVALENCE_UNPROVEN"
    R_JOINT_EQUIVALENCE_UNPROVEN = "R_JOINT_EQUIVALENCE_UNPROVEN"
    R_TRANSFORM_INVALID = "R_TRANSFORM_INVALID"
    R_WORKSPACE_VIOLATION = "R_WORKSPACE_VIOLATION"
    R_IK_UNREACHABLE = "R_IK_UNREACHABLE"
    R_SINGULARITY = "R_SINGULARITY"
    R_BRANCH_DISCONTINUITY = "R_BRANCH_DISCONTINUITY"
